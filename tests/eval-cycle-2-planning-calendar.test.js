'use strict';
const assert=require('node:assert/strict');
const P=require('../planning-core.js');
const profile={profileId:'personal',enterprise:{renewals:[]}};
P.saveRenewal(profile,{name:'Godišnji; paket, Ž'+'č'.repeat(65),cadence:'annual',anchorDate:'2024-02-29',amount:120,currency:'EUR'});
P.saveRenewal(profile,{name:'Mjesec',cadence:'monthly',anchorDate:'2026-01-31',amount:12,currency:'EUR'});
P.saveRenewal(profile,{name:'Proba',cadence:'trial',anchorDate:'2026-09-10',amount:50,currency:'EUR'});
const result=P.buildRenewalCalendar(profile,{referenceDate:'2026-09-07',now:new Date('2026-09-07T12:00:00Z')});
assert.equal(result.count,3);assert.match(result.filename,/Pretplate_Podsjetnici_Osobni_2026-09-07\.ics/);
assert.ok(result.content.endsWith('\r\n'));
assert.match(result.content,/TRIGGER;RELATED=START:-P3D/);
assert.match(result.content,/RRULE:FREQ=YEARLY;BYMONTH=2;BYMONTHDAY=-1/);
assert.match(result.content,/RRULE:FREQ=MONTHLY;BYMONTHDAY=28,29,30,31;BYSETPOS=-1/);
assert.equal((result.content.match(/BEGIN:VALARM/g)||[]).length,3);
assert.equal((result.content.match(/RRULE:/g)||[]).length,2,'free trials are one-off events');
assert.ok(result.content.split('\r\n').every(line=>Buffer.byteLength(line)<=75),'iCalendar folds UTF-8 lines at 75 octets');
const unfolded=result.content.replace(/\r\n /g,'');
assert.match(unfolded,/Godišnji\\; paket\\, Ž/);
assert.match(unfolded,/DTSTART;VALUE=DATE:20270910|DTSTART;VALUE=DATE:20260910/);
const nextYear=P.buildRenewalCalendar(profile,{referenceDate:'2027-09-07',now:new Date('2027-09-07T12:00:00Z')});
const originalIds=[...result.content.matchAll(/UID:([^\r]+)/g)].map(match=>match[1]);
const nextIds=[...nextYear.content.matchAll(/UID:([^\r]+)/g)].map(match=>match[1]);
assert.equal(nextYear.count,2,'expired free trial is not exported into the future');
assert.ok(nextIds.every(id=>originalIds.includes(id)),'repeated exports retain stable calendar IDs');
assert.equal(P.buildRenewalCalendar(profile,{profileId:'business',referenceDate:'2026-09-07'}).count,0);
const malicious={profileId:'personal',enterprise:{renewals:[{id:'bad',name:'BAD\nEND:VEVENT\nBEGIN:VEVENT',amount:10,currency:'EUR',cadence:'trial',anchorDate:'2026-09-10'}]}};
const safe=P.buildRenewalCalendar(malicious,{referenceDate:'2026-09-07'}).content;
assert.equal((safe.match(/\r\nBEGIN:VEVENT\r\n/g)||[]).length,1,'text cannot inject calendar events');
assert.equal((safe.match(/\r\nEND:VEVENT\r\n/g)||[]).length,1);
process.stdout.write('Planning cycle 2: calendar alarms, annual/month-end recurrence, leap days, deduplication, UTF-8 folding and injection resistance passed.\n');
